      (* deferred by tools/lazify-merge.py; see that file *)
      let merge' =
        lazy
          (let merge_owner_address =
             Runtime'.Merge.merge
               Runtime'.Spec.(
                 basic
                   ( (1, "owner_address", "ownerAddress"),
                     bytes,
                     Bytes.of_string {||} ))
           in
           let merge_exchange_id =
             Runtime'.Merge.merge
               Runtime'.Spec.(
                 basic ((2, "exchange_id", "exchangeId"), int64, 0L))
           in
           let merge_token_id =
             Runtime'.Merge.merge
               Runtime'.Spec.(
                 basic ((3, "token_id", "tokenId"), bytes, Bytes.of_string {||}))
           in
           let merge_quant =
             Runtime'.Merge.merge
               Runtime'.Spec.(basic ((4, "quant", "quant"), int64, 0L))
           in
           let merge_expected =
             Runtime'.Merge.merge
               Runtime'.Spec.(basic ((5, "expected", "expected"), int64, 0L))
           in
           fun t1 t2 ->
             {
               owner_address =
                 merge_owner_address t1.owner_address t2.owner_address;
               exchange_id = merge_exchange_id t1.exchange_id t2.exchange_id;
               token_id = merge_token_id t1.token_id t2.token_id;
               quant = merge_quant t1.quant t2.quant;
               expected = merge_expected t1.expected t2.expected;
             })
      in
      fun t1' t2' -> (Lazy.force merge') t1' t2'

    let spec () =
      Runtime'.Spec.(
        basic ((1, "owner_address", "ownerAddress"), bytes, Bytes.of_string {||})
        ^:: basic ((2, "exchange_id", "exchangeId"), int64, 0L)
        ^:: basic ((3, "token_id", "tokenId"), bytes, Bytes.of_string {||})
        ^:: basic ((4, "quant", "quant"), int64, 0L)
        ^:: basic ((5, "expected", "expected"), int64, 0L)
        ^:: nil)

    let to_proto' =
      let serialize =
        Runtime'.apply_lazy (fun () -> Runtime'.Serialize.serialize (spec ()))
      in
      fun writer { owner_address; exchange_id; token_id; quant; expected } ->
